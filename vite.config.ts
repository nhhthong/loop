import { defineConfig, type Plugin } from 'vite';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/** Cache-first service worker for hashed bundles + models/textures/audio; the HTML stays network-first.
 *  The cache name carries a build id (bundle file names + content of the cached public folders), so a new deploy
 *  gets a new cache and the old one is deleted on activate. */
function swPlugin(): Plugin {
  const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)])).sort();
  const SW = (id: string) => `// generated by vite.config.ts (build ${id})
const CACHE = 'loop-${id}';
const ROOT = new URL('./', self.location).pathname;
const CACHED = /^(assets|models|textures|audio)\\//;
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(
  caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('loop-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== self.location.origin || r.headers.has('range')) return;
  if (r.mode === 'navigate') { // network-first: a new deploy is never served stale
    e.respondWith(fetch(r).then((res) => { if (res.ok) { const c = res.clone(); caches.open(CACHE).then((x) => x.put(r, c)); } return res; }).catch(() => caches.match(r)));
    return;
  }
  if (!u.pathname.startsWith(ROOT) || !CACHED.test(u.pathname.slice(ROOT.length))) return;
  e.respondWith(caches.open(CACHE).then(async (cache) => {
    const hit = await cache.match(r);
    if (hit) return hit;
    const res = await fetch(r);
    if (res.status === 200) cache.put(r, res.clone());
    return res;
  }));
});
`;
  return {
    name: 'loop-sw',
    apply: 'build',
    generateBundle(_o, bundle) {
      const h = createHash('sha1');
      h.update(Object.keys(bundle).sort().join('|'));
      for (const dir of ['models', 'textures', 'audio']) {
        try { for (const f of walk(join('public', dir))) { h.update(f); h.update(readFileSync(f)); } } catch { /* folder missing */ }
      }
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: SW(h.digest('hex').slice(0, 10)) });
    },
  };
}

export default defineConfig({
  base: './', // relative: works at any sub-path (GitHub Pages /loop/)
  server: { host: true },
  plugins: [swPlugin()],
  build: {
    target: 'es2022',
    chunkSizeWarningLimit: 4000,
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (id.includes('@dimforge/rapier3d')) return 'rapier';
          if (id.includes('node_modules/postprocessing') || id.includes('node_modules/n8ao')) return 'postfx';
          if (id.includes('node_modules/three')) return 'three';
        },
      },
    },
  },
  optimizeDeps: { exclude: ['@dimforge/rapier3d-compat'] },
});
