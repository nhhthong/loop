import * as THREE from 'three';
import { Assets } from '../engine/Assets';
import { Hands } from '../player/Hands';
const r = new THREE.WebGLRenderer({ canvas: document.getElementById('c') as HTMLCanvasElement, antialias: true });
r.setSize(innerWidth, innerHeight); r.toneMapping = THREE.AgXToneMapping;
const scene = new THREE.Scene(); scene.background = new THREE.Color(0x2a2622);
scene.add(new THREE.HemisphereLight(0xfff0e0, 0x302820, 1.2)); const dl = new THREE.DirectionalLight(0xffe0c0, 2.5); dl.position.set(1, 2, 1); scene.add(dl);
const q = new URLSearchParams(location.search);
const num = (k: string, d: number) => +(q.get(k) ?? d);
const cam = new THREE.PerspectiveCamera(num('fov', 70), innerWidth / innerHeight, 0.01, 50);
scene.add(cam);
const assets = new Assets();
const g = (await assets.model('/models/hands_bugs/male_hand_scan.glb'))!;
const hands = new Hands();
await hands.load(g, cam);
hands.setVisible(true);
hands.target.set(num('tx', 0.06), num('ty', -0.1), num('tz', -0.36));
hands.f.set(num('fx', -0.1), num('fy', 1), num('fz', -0.15)).normalize();
hands.b.set(num('bx', 0), num('by', 0), num('bz', -1)).normalize();
hands.roll = num('roll', 0);
const c = num('curl', 0.15); hands.curls = [c, c, c, c, c * 0.6];
for (let i = 0; i < 60; i++) hands.update(0.1);
r.render(scene, cam);
document.title = 'ready';
